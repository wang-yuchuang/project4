/*=============================================================================================
** @Name      : void BSPWatchDogInit(void)
** @Input     : void
** @Output    : 初始化结果 TRUE:成功 FALSE:失败
** @Function  : 软件和硬件看门狗模块初始化
** @The notes : 软狗3s内需要喂狗一次，硬件1.6s内需要喂狗一次，不然复位
**===========================================================================================*/
void BSPWatchDogInit(void)
{
    //模块未使能不进行初始化
    if(1 != gBSPFunCfg.Bits.WDOGEn)
    {   
        return;
    }
    MX_IWDG_Init();//软件独立看门狗，3s内需要喂狗一次，不然复位
}

/*=============================================================================================
** @Name      : void BSPWatchDogRefresh(void)
** @Input     : void
** @Output    : void
** @Function  : 看门狗刷新
** @The notes : 看门狗喂狗,用户调用
**===========================================================================================*/
void BSPWatchDogRefresh(void)
{
    //内部看门狗未初始化
    if(1 != gBSPFunCfg.Bits.WDOGEn)
    {   
        return;
    }
    //软件看门狗喂狗
    HAL_IWDG_Refresh(&hiwdg);
}

